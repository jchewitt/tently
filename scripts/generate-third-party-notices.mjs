// Modified for standalone extraction; see docs/extraction-manifest.json.
import { spawnSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { pnpmInvocation } from './package-manager.mjs';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const toolkitRoot = resolve(scriptDirectory, '..');
const repositoryRoot = toolkitRoot;
const checkOnly = process.argv.includes('--check');
const allowedLicenses = new Set(['Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', 'ISC', 'MIT']);
const reviewed = JSON.parse(await readFile(resolve(toolkitRoot, 'reviewed-licenses.json'), 'utf8'));
for (const record of reviewed) {
  const text = await readFile(resolve(toolkitRoot, record.notice));
  if (createHash('sha256').update(text).digest('hex') !== record.noticeSha256) {
    throw new Error(`Reviewed license notice changed: ${record.notice}`);
  }
}
const packageTargets = [
  {
    name: '@launch-echo/tently-core',
    path: resolve(toolkitRoot, 'packages', 'core', 'THIRD_PARTY_NOTICES.md'),
    includeExternalTools: false,
  },
  {
    name: '@launch-echo/tently',
    path: resolve(toolkitRoot, 'THIRD_PARTY_NOTICES.md'),
    includeExternalTools: true,
  },
];

function isAllowedLicenseExpression(expression) {
  const tokens = expression.replaceAll('(', ' ').replaceAll(')', ' ').split(/\s+/).filter(Boolean);
  return (
    tokens.length > 0 &&
    tokens.every((token) => token === 'AND' || token === 'OR' || allowedLicenses.has(token))
  );
}

function pnpmCommand(args) {
  const invocation = pnpmInvocation(args);
  const result = spawnSync(invocation.command, invocation.args, {
    cwd: repositoryRoot,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  if (result.status !== 0) {
    throw new Error(result.error?.message || result.stderr?.trim() || result.stdout?.trim() || `pnpm exited ${result.status}`);
  }
  return result.stdout;
}

function dependencyRows(report) {
  const rows = [];
  const unsupported = [];
  for (const [license, dependencies] of Object.entries(report)) {
    for (const dependency of dependencies) {
      if (['@launch-echo/tently', '@launch-echo/tently-core'].includes(dependency.name)) continue;
      const exceptions = dependency.versions.map((version) => reviewed.find((record) =>
        record.name === dependency.name && record.version === version && record.expression === license));
      if (!isAllowedLicenseExpression(license) && !exceptions.every(Boolean)) {
        unsupported.push(`${dependency.name}: ${license}`);
      }
      rows.push({
        name: dependency.name,
        versions: [...dependency.versions].sort().join(', '),
        license,
        homepage: dependency.homepage ?? '',
      });
    }
  }
  if (unsupported.length > 0) {
    throw new Error(
      `Unsupported third-party licenses: ${[...new Set(unsupported)].sort().join(', ')}`,
    );
  }
  return rows.sort((left, right) =>
    `${left.license}:${left.name}`.localeCompare(`${right.license}:${right.name}`),
  );
}

function markdown(target, rows, externalTools) {
  const lines = [
    '# Third-Party Notices',
    '',
    '<!-- Modified for standalone extraction; dependency versions reflect this distribution. -->',
    '',
    `Generated for \`${target.name}\` by \`pnpm context-graph:licenses\`.`,
    'Do not edit this file manually.',
    '',
    '## Node production dependency inventory',
    '',
    '<!-- prettier-ignore -->',
    '| Package | Version(s) | License | Homepage |',
    '| --- | --- | --- | --- |',
  ];
  if (rows.length === 0) lines.push('| (none) | — | — | — |');
  for (const row of rows) {
    const homepage = row.homepage ? `[link](${row.homepage})` : '—';
    lines.push(`| \`${row.name}\` | ${row.versions} | ${row.license} | ${homepage} |`);
  }
  if (target.includeExternalTools) {
    lines.push('', '## Scoped license selections', '');
    for (const record of reviewed) {
      lines.push(`- \`${record.name}@${record.version}\`: ${record.selectedLicense}; notice: [${record.notice}](${record.notice}).`);
    }
    lines.push(
      '',
      '## Referenced build and runtime tools',
      '',
      'These tools are downloaded or invoked by configuration and are not bundled in the npm',
      'packages. Their distribution posture remains explicit for extraction and release review.',
      '',
      '<!-- prettier-ignore -->',
      '| Tool | Version | License posture | Distribution |',
      '| --- | --- | --- | --- |',
    );
    for (const tool of externalTools) {
      lines.push(
        `| [${tool.name}](${tool.homepage}) | ${tool.version} | ${tool.license} | ${tool.distribution} |`,
      );
    }
  }
  return `${lines.join('\n')}\n`;
}

const externalTools = JSON.parse(
  await readFile(resolve(toolkitRoot, 'third-party-tools.json'), 'utf8'),
);
let failed = false;
for (const target of packageTargets) {
  const reportText = pnpmCommand([
    'licenses',
    'list',
    '--filter',
    target.name,
    '--prod',
    '--json',
  ]).trim();
  const report = reportText === 'No licenses in packages found' ? {} : JSON.parse(reportText);
  const expected = markdown(target, dependencyRows(report), externalTools);
  if (checkOnly) {
    const current = await readFile(target.path, 'utf8').catch(() => '');
    if (current !== expected) {
      console.error(`${target.path} is stale; run pnpm context-graph:licenses`);
      failed = true;
    }
  } else {
    await writeFile(target.path, expected, 'utf8');
  }
}
if (failed) process.exitCode = 1;
